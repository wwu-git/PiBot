import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const SESSION_SOURCE_SHA256 = "2628f797997ea3a133573ff8f36a050cdc1d74d2d346b856f328e5e7da42aba1";

/** Keep the add-only adapter tied to pi's exact existing hydration/persistence constructor. */
export function generateAsyncSession(root: string) {
  const version = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")).version;
  const source = readFileSync(resolve(root, "dist/core/session-manager.js"), "utf8");
  const sha256 = createHash("sha256").update(source).digest("hex");
  if (version !== "1.6.0" || sha256 !== SESSION_SOURCE_SHA256)
    throw new Error("pi_async_session_source_changed");
  const functions = ["parseSessionEntryLine", "getSessionHeaderCwd"].map((name) => {
    const matches = [...source.matchAll(new RegExp(`^function ${name}\\([^]*?^\\}`, "gm"))];
    if (matches.length !== 1) throw new Error("pi_async_session_helper_changed");
    return matches[0]?.[0];
  });
  if (
    !source.includes(
      "constructor(cwd, sessionDir, sessionFile, persist, newSessionOptions, preloadedFileEntries)",
    ) ||
    !source.includes(
      "const entries = preloadedFileEntries ?? loadEntriesFromFile(this.sessionFile);",
    )
  )
    throw new Error("pi_async_session_constructor_changed");
  return {
    source: { file: "dist/core/session-manager.js", sha256 },
    code: `// Add-only Pi Bot adapter for pi-coding-agent 1.6.0 (MIT).
// Generated by packages/agent/scripts/pi-async-session.ts; preserve the upstream license.
// The original SDK files remain unchanged. Its constructor owns migration, indexing and writes.
import { appendFileSync } from "node:fs";
import { open } from "node:fs/promises";
import { resolve } from "node:path";
import { StringDecoder } from "node:string_decoder";
import { setImmediate as yieldToLoop } from "node:timers/promises";
import { SessionManager } from "./core/session-manager.js";
import { normalizePath, resolvePath } from "./utils/paths.js";

${functions.join("\n")}

// Awaiting an already-resolved promise would keep RPC callbacks behind the microtask queue.
async function loadEntriesAsync(path, signal) {
    signal?.throwIfAborted();
    let file;
    try {
        file = await open(path, "r");
    } catch (error) {
        if (error.code === "ENOENT") return { entries: undefined, repairNewline: false };
        throw error;
    }
    const entries = [];
    let tail;
    try {
        const buffer = Buffer.allocUnsafe(1024 * 1024);
        const decoder = new StringDecoder("utf8");
        let lineChunks = [];
        let batchStarted = performance.now();
        const consume = async (chunk) => {
            let start = 0;
            let newline = chunk.indexOf("\\n");
            while (newline !== -1) {
                signal?.throwIfAborted();
                lineChunks.push(chunk.slice(start, newline));
                const entry = parseSessionEntryLine(lineChunks.join(""));
                if (entry) entries.push(entry);
                lineChunks = [];
                start = newline + 1;
                if (performance.now() - batchStarted >= 8) {
                    await yieldToLoop(undefined, { signal });
                    signal?.throwIfAborted();
                    batchStarted = performance.now();
                }
                newline = chunk.indexOf("\\n", start);
            }
            if (start < chunk.length) lineChunks.push(chunk.slice(start));
        };
        while (true) {
            signal?.throwIfAborted();
            const { bytesRead } = await file.read(buffer, 0, buffer.length, null);
            signal?.throwIfAborted();
            if (bytesRead === 0) break;
            await consume(decoder.write(buffer.subarray(0, bytesRead)));
            // Bound each I/O/parse batch even when the entire file is in the filesystem cache.
            await yieldToLoop(undefined, { signal });
            batchStarted = performance.now();
        }
        await consume(decoder.end());
        tail = lineChunks.join("");
        const entry = parseSessionEntryLine(tail);
        if (entry) entries.push(entry);
    } finally {
        await file.close();
    }
    signal?.throwIfAborted();
    // Match loadEntriesFromFile: malformed physical lines are skipped; a non-header file is
    // invalid and must be rejected by the SDK without repairing or replacing its contents.
    if (entries.length === 0) return { entries, repairNewline: false };
    const header = entries[0];
    if (header.type !== "session" || typeof header.id !== "string")
        return { entries: [], repairNewline: false };
    return { entries, repairNewline: !!tail };
}

/** Async parsing, followed by the exact pinned SDK's existing preloaded-entries constructor. */
export async function openSessionAsync(path, sessionDir, cwdOverride, signal) {
    const resolvedPath = resolvePath(path);
    const { entries, repairNewline } = await loadEntriesAsync(resolvedPath, signal);
    const header = entries?.[0];
    const cwd = cwdOverride ?? (header ? getSessionHeaderCwd(header) : undefined) ?? process.cwd();
    const dir = sessionDir ? normalizePath(sessionDir) : resolve(resolvedPath, "..");
    signal?.throwIfAborted();
    // The commit boundary has no await: an aborted read never repairs the file, creates a
    // directory, migrates a header, or installs manager state. Preserve SDK newline repair.
    if (repairNewline) appendFileSync(resolvedPath, "\\n");
    return new SessionManager(cwd, dir, resolvedPath, true, undefined, entries);
}
`,
    types: `import type { SessionManager } from "./core/session-manager.js";
export declare function openSessionAsync(path: string, sessionDir?: string, cwdOverride?: string, signal?: AbortSignal): Promise<SessionManager>;
`,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const { values } = parseArgs({
    options: { source: { type: "string" }, output: { type: "string" } },
  });
  if (!values.source || !values.output)
    throw new Error("pi_async_session_source_and_output_required");
  const result = generateAsyncSession(resolve(values.source));
  writeFileSync(values.output, result.code);
  writeFileSync(values.output.replace(/\.js$/u, ".d.ts"), result.types);
  console.log(JSON.stringify({ output: values.output, source: result.source }));
}
